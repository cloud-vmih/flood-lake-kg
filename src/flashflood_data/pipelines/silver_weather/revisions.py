"""Stable weather observation identity across source products and revisions."""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from datetime import datetime, timezone
from hashlib import sha256

_UTC = timezone.utc  # noqa: UP017 - Spark image currently uses Python 3.10.
_EPOCH = datetime(1970, 1, 1, tzinfo=_UTC)
_ALIAS = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_TIME_FIELDS = {"model_run_time", "valid_time", "window_start", "window_end"}
_KEY_FIELDS = (
    "basin_id",
    "basin_version",
    "source_id",
    "source_product",
    "source_grid_version",
    "source_cycle_id",
    "model_run_time",
    "valid_time",
    "window_start",
    "window_end",
    "variable",
    "vertical_level",
    "source_revision",
)


def _epoch_micros(value: datetime, field: str) -> int:
    if value.tzinfo is None or value.utcoffset() != _UTC.utcoffset(value):
        raise ValueError(f"{field} must be a timezone-aware UTC timestamp")
    delta = value - _EPOCH
    return ((delta.days * 86400 + delta.seconds) * 1_000_000) + delta.microseconds


def weather_business_key(row_without_hash: Mapping[str, object]) -> str:
    """Hash the complete observation identity, excluding mutable QA and slice IDs.

    The ordered JSON payload is also generated by ``weather_business_key_sql``.
    Timestamps use UTC epoch microseconds so Spark and Python agree on precision.
    """
    identity: dict[str, str | int | None] = {}
    for field in _KEY_FIELDS:
        if field not in row_without_hash:
            raise ValueError(f"weather business key requires {field}")
        value = row_without_hash[field]
        if field in _TIME_FIELDS:
            if value is None and field == "model_run_time":
                identity[field] = None
            elif isinstance(value, datetime):
                identity[field] = _epoch_micros(value, field)
            else:
                raise ValueError(f"{field} must be a timezone-aware UTC timestamp")
        elif field == "source_revision":
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise ValueError("source_revision must be a non-negative integer")
            identity[field] = value
        elif not isinstance(value, str) or not value.strip():
            raise ValueError(f"{field} must be non-empty text")
        else:
            identity[field] = value
    payload = json.dumps(identity, ensure_ascii=False, separators=(",", ":"))
    return sha256(payload.encode("utf-8")).hexdigest()


def weather_business_key_sql(alias: str) -> str:
    """Spark SQL expression for the same identity used by ``weather_business_key``.

    NOW, Standard, ERA5 and IFS have separate identities. Silver suppresses
    ERA5 rain when valid GSMaP covers its exact basin/window; surviving source
    products/cycles/revisions retain their own observation hashes.
    """
    if _ALIAS.fullmatch(alias) is None:
        raise ValueError("unsafe Spark SQL alias")
    fields = []
    for name in _KEY_FIELDS:
        expression = f"{alias}.{name}"
        if name in _TIME_FIELDS:
            expression = f"unix_micros({expression})"
        elif name == "source_revision":
            expression = f"CAST({expression} AS INT)"
        fields.extend((f"'{name}'", expression))
    return (
        f"sha2(to_json(named_struct({', '.join(fields)}), "
        "map('ignoreNullFields', 'false')), 256)"
    )
